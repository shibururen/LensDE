def normalize_search_trace(options: dict) -> None:
    """Normalize initial-search coverage, manufacturability and trace sampling defaults."""
    options.setdefault('initial_search_trace_policy', 'soft_coverage')
    options.setdefault('initial_search_min_field_coverage', 1.0)
    options.setdefault('initial_search_min_system_coverage', 1.0)
    options.setdefault('initial_search_min_coverage_for_image_merit', 0.5)
    options.setdefault('initial_search_trace_failure_weight', 5.0)
    options.setdefault('initial_search_coverage_failure_weight', 800.0)
    options.setdefault('initial_search_aim_failure_weight', 2.0)
    options.setdefault('initial_search_backward_failure_weight', 10.0)
    options.setdefault('initial_search_require_chief_ray', True)
    options.setdefault('initial_search_require_off_axis_field_coverage', True)
    options.setdefault('initial_search_hard_trace_gate_weight', 20000.0)
    options.setdefault('initial_search_trace_progress_weight', 1000.0)
    options.setdefault('initial_search_chief_progress_weight', 2000.0)
    options.setdefault('initial_search_trace_priority_weight', 150.0)
    options.setdefault('initial_search_first_order_weight_scale', 1.0)
    options.setdefault('initial_search_spot_weight_scale', 1.0)
    options.setdefault('initial_search_first_order_edge_weight', 0.0)
    options.setdefault('initial_search_first_order_min_edge', 1.0)
    for key, default in state.THICKNESS_CONSTRAINT_DEFAULTS:
        options.setdefault('initial_search_' + key, default)
    for key, default in state.MANUFACTURING_RATIO_CONSTRAINT_DEFAULTS:
        options.setdefault('initial_search_' + key, default)
    options.setdefault('initial_search_trace_rms_upper', 0.0)
    options.setdefault('initial_search_trace_rays', 3)
    options.setdefault('initial_search_trace_arms', 6)
    options.setdefault('initial_search_trace_distribution', 'gaussian_ring_arm')
    options.setdefault('initial_search_include_stop_air_thickness', True)
    options.setdefault('initial_search_stop_air_thickness_min', 0.1)
    options.setdefault('initial_search_stop_air_thickness_max', 27.0)
