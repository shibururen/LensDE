from .. import initialization as _lensde_initialization

def normalize_runtime_and_refresh(project: dict, system: dict, merit: dict, glass_search: dict) -> dict:
    """Bind the existing options mapping, apply plastic policy, then runtime and refresh defaults."""
    options = project.setdefault('options', {})
    if _lensde_commands.option_truthy(options.get('initial_search_post_asphere_plastic_enabled'), False):
        glass_search['enabled'] = False
        selected_material_indices = set(_lensde_initialization.selected_post_asphere_material_surface_indices(system, options))
        for surface_cfg in glass_search.get('surface_configs', []):
            if not isinstance(surface_cfg, dict):
                continue
            try:
                surface_index = int(surface_cfg.get('surface_index', -1))
            except (TypeError, ValueError):
                continue
            surface_cfg['enabled'] = surface_index in selected_material_indices
    options.setdefault('spot_distribution', 'uniform')
    options.setdefault('spot_rays', 41)
    options.setdefault('spot_arms', 64)
    options.setdefault('spot_sampling_seed', merit.get('sampling_seed', 1))
    options.setdefault('spot_scale_mode', 'shared')
    options.setdefault('use_cuda', False)
    options.setdefault('cpp_timeout', state.DEFAULT_CPP_TIMEOUT)
    options.setdefault('hammer_attempts', 240)
    options.setdefault('hammer_seed', 0)
    options.setdefault('hammer_pre_polish_iter', 12)
    options.setdefault('hammer_hot_polish_iter', 8)
    options.setdefault('hammer_cold_polish_iter', 24)
    options.setdefault('hammer_final_polish_iter', 80)
    options.setdefault('hammer_temp_start', 0.05)
    options.setdefault('hammer_temp_end', 1e-06)
    options.setdefault('hammer_temp_power', 2.0)
    options.setdefault('hammer_step_start', 0.08)
    options.setdefault('hammer_step_end', 0.004)
    options.setdefault('hammer_glass_rate_start', 0.2)
    options.setdefault('hammer_glass_rate_end', 0.03)
    options.setdefault('hammer_glass_random_rate', 0.03)
    options.setdefault('hammer_glass_neighbor_count', 8)
    options.setdefault('hammer_weight_continuous', 0.3)
    options.setdefault('hammer_weight_gap', 0.18)
    options.setdefault('hammer_weight_bend', 0.22)
    options.setdefault('hammer_weight_glass', 0.18)
    options.setdefault('hammer_weight_glass_repair', 0.12)
    options.setdefault('hammer_image_spot_weight', 1000.0)
    options.setdefault('hammer_merit_weight', 0.25)
    options.setdefault('hammer_trace_penalty_weight', 100.0)
    options.setdefault('hammer_constraint_penalty_weight', 25.0)
    options.setdefault('hammer_first_order_penalty_weight', 25.0)
    options.setdefault('hammer_write_trace', True)
    options.setdefault('hammer_reject_trace_infeasible', False)
    options.setdefault('refresh_generation_mode', 'restricted_perturbation')
    options.setdefault('refresh_trace_feasible_gate', True)
    options.setdefault('refresh_target_count', 0)
    options.setdefault('refresh_max_candidates', 0)
    options.setdefault('refresh_max_seconds', 0.0)
    options.setdefault('refresh_parent_count', 8)
    options.setdefault('refresh_curvature_rel', 0.2)
    options.setdefault('refresh_air_thickness_rel', 0.15)
    options.setdefault('refresh_glass_thickness_rel', 0.08)
    options.setdefault('refresh_curvature_abs', 0.05)
    options.setdefault('refresh_air_thickness_abs', 5.0)
    options.setdefault('refresh_glass_thickness_abs', 0.5)
    options.setdefault('refresh_perturb_material_variables', True)
    options.setdefault('refresh_seed_pool_fraction', 0.0)
    options.setdefault('refresh_seed_pool_perturbation', 0.0)
    options.setdefault('refresh_trace_archive_enabled', True)
    options.setdefault('refresh_trace_archive_capacity', 4096)
