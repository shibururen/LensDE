def normalize_search_strategy(options: dict, *, finite_float) -> None:
    """Apply the retained run-profile and JADE/mating choices before basin policy defaults."""
    options['initial_search_run_profile'] = _lensde_defaults.canonical_initial_search_run_profile(options.get('initial_search_run_profile', 'single_pass_demo'))
    options.setdefault('initial_search_merit_strategy', 'full')
    options.setdefault('initial_search_full_rescore_after_search', False)
    strategy_value = str(options.get('initial_search_merit_strategy', '')).lower().replace('-', '_')
    if strategy_value in {'current', 'search_only'}:
        options['initial_search_merit_strategy'] = 'full'
    elif strategy_value in {'full_merit', 'complete'}:
        options['initial_search_merit_strategy'] = 'full'
    elif strategy_value in {'stage', 'staged_full'}:
        options['initial_search_merit_strategy'] = 'staged'
    elif strategy_value not in {'search', 'full', 'staged'}:
        options['initial_search_merit_strategy'] = 'full'
    else:
        options['initial_search_merit_strategy'] = strategy_value
    options.pop('initial_search_generations', None)
    options.setdefault('initial_search_hybrid_outer', 10)
    options.setdefault('initial_search_hybrid_de_gen', 120)
    options.setdefault('initial_search_hybrid_parents', 10)
    options.setdefault('initial_search_polish_candidates', 32)
    options.setdefault('initial_search_polish_refill_max_extra', int(options.get('initial_search_polish_candidates', 32) or 32))
    options.setdefault('initial_search_polish_selection', 'topology_balanced')
    options['initial_search_de_variant'] = 'jade_pbest_archive'
    options.setdefault('initial_search_track_population_diversity', False)
    options.setdefault('initial_search_constraint_handling', 'scalar_merit')
    options.setdefault('initial_search_hard_first_order', False)
    options.setdefault('initial_search_first_order_epsilon', 1e-05)
    options.setdefault('initial_search_pbest_fraction', 0.1)
    options['initial_search_pbest_scope'] = 'global'
    options['initial_search_pbest_basin_rate'] = min(1.0, max(0.0, finite_float(options.get('initial_search_pbest_basin_rate'), 0.0)))
    options['initial_search_pbest_same_key_rate'] = min(1.0, max(0.0, finite_float(options.get('initial_search_pbest_same_key_rate'), 0.0)))
    options['initial_search_pbest_global_rate'] = min(1.0, max(0.0, finite_float(options.get('initial_search_pbest_global_rate'), 1.0)))
    options.setdefault('initial_search_pbest_global_fallback', True)
    options.setdefault('initial_search_pbest_basin_nearest_fallback', False)
    options['initial_search_pbest_basin_rate'] = 0.0
    options['initial_search_pbest_same_key_rate'] = 0.0
    options['initial_search_pbest_global_rate'] = 1.0
    options['initial_search_de_mating_scope'] = 'global'
    options['initial_search_de_mating_local_rate'] = min(1.0, max(0.0, finite_float(options.get('initial_search_de_mating_local_rate'), 0.0)))
    options['initial_search_de_mating_min_pool'] = max(4, int(finite_float(options.get('initial_search_de_mating_min_pool'), 4)))
    options['initial_search_de_mating_local_rate'] = 0.0
    options['initial_search_de_mating_min_pool'] = 4
    options['initial_search_de_mating_strict_local'] = False
    options['initial_search_basin_active_diversity'] = False
    options['initial_search_basin_balanced_refresh'] = False


