    if int(finite_float(merit.get('conic_coefficient_constraint_version'), 0)) < 2:
        legacy_tol = finite_float(merit.get('quality_conic_coefficient_tol'), 10.0)
        legacy_weight = finite_float(merit.get('conic_coefficient_penalty_weight'), 0.5)
        if abs(legacy_tol - 10.0) <= 1e-12:
            merit['quality_conic_coefficient_tol'] = 1.0
        if abs(legacy_weight - 0.5) <= 1e-12:
            merit['conic_coefficient_penalty_weight'] = 5.0
        merit['conic_coefficient_constraint_version'] = 2
    merit.setdefault('quality_conic_coefficient_tol', 1.0)
    merit['quality_conic_coefficient_tol'] = max(1e-09, finite_float(merit.get('quality_conic_coefficient_tol'), 1.0))
    merit.setdefault('conic_coefficient_penalty_enabled', True)
    merit.setdefault('conic_coefficient_lower', -100.0)
    merit.setdefault('conic_coefficient_upper', 100.0)
    merit.setdefault('conic_coefficient_penalty_weight', 5.0)
    merit.setdefault('quality_distortion_tol', 0.01)
    merit['distortion_model'] = _lensde_defaults.canonical_distortion_model(merit.get('distortion_model'), 'auto')
